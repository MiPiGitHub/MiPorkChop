import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const html=fs.readFileSync(new URL('../src/viewer.html',import.meta.url),'utf8');
const nodes={};
let failStatus=false;
const context=vm.createContext({document:{getElementById:id=>nodes[id]??={value:'',addEventListener(){}}},setInterval(){},fetch:async path=>{
 if(path==='/api/public-status'&&failStatus)throw Error('offline');
 return new Promise(()=>{});
}});
vm.runInContext(html.match(/<script>([\s\S]*?)<\/script>/)[1],context);
vm.runInContext("last={state:'OPEN',lastSeen:new Date().toISOString(),lastChanged:new Date(Date.now()-1800000).toISOString()};attendance={available:true,canCheckIn:true,count:4,comingCount:0};attendanceBusy=false;motdMessage='Game is on';render();renderAttendance();",context);
assert.equal(nodes['attendance-count'].textContent,'4 here');
assert.equal(nodes['coming-count'].textContent,'0 on the way');
assert.equal(nodes['attendance-note'].textContent,'');
assert.equal(nodes.detail.hidden,true);
assert.equal(nodes['attendance-section'].hidden,false);
assert.equal(nodes['motd-section'].hidden,false);
assert.equal(nodes['unavailable-stamp'].hidden,true);
assert.match(nodes.since.textContent,/Open since/);
assert(!nodes.since.textContent.includes('•'));
assert.match(nodes['changed-detail'].textContent,/Last state change:/);
vm.runInContext("last.state='CLOSED';render();renderAttendance();",context);
assert.equal(nodes['attendance-section'].hidden,true);
assert.equal(nodes['closed-note'].hidden,false);
assert.equal(nodes['motd-section'].hidden,true);
assert.equal(nodes.detail.hidden,true);
vm.runInContext("last.state='OPEN';last.lastSeen=new Date(Date.now()-451000).toISOString();render();renderAttendance();",context);
assert.equal(nodes['attendance-section'].hidden,true);
assert.equal(nodes['motd-section'].hidden,true);
assert.equal(nodes['closed-note'].hidden,true);
assert.equal(nodes['unavailable-stamp'].hidden,false);
assert.match(nodes['unavailable-stamp'].textContent,/Last confirmed/);
assert.equal(nodes['attendance-button'].hidden,true);
// A network failure preserves the last confirmed timestamp but hides stale interactions.
vm.runInContext("last.lastSeen=new Date().toISOString();render();renderAttendance();",context);
failStatus=true;
await vm.runInContext('refresh()',context);
vm.runInContext('renderAttendance()',context);
assert.equal(nodes.state.textContent,'SERVICE UNAVAILABLE');
assert.equal(nodes['attendance-section'].hidden,true);
assert.equal(nodes['attendance-button'].hidden,true);
assert.match(nodes['unavailable-stamp'].textContent,/Last confirmed/);
assert.match(nodes.detail.textContent,/couldn’t confirm/);
// Semantic order and collapsed secondary controls.
assert(html.indexOf('id="motd-section"')<html.indexOf('id="attendance-section"'));
assert(html.indexOf('id="attendance-section"')<html.indexOf('id="options"'));
assert(html.indexOf('id="options"')<html.indexOf('id="nickname-settings"'));
assert(html.indexOf('id="options"')<html.indexOf('Add to Home Screen'));
assert(html.indexOf('id="options"')<html.indexOf('id="status-details"'));
assert(!/<details[^>]*\sopen(?:[\s>])/.test(html));
assert.match(html,/id="attendance-button" class="primary"/);
console.log('PASS: compact open view, collapsed settings, closed/unavailable states, primary action and retained last-confirmed time on network errors.');
// Manual fallback works even when the Pi has never sent a heartbeat.
vm.runInContext("last={state:'OPEN',source:'manual',lastSeen:null,confirmedAt:new Date().toISOString(),lastChanged:new Date().toISOString()};statusFetchFailed=false;render();renderAttendance();",context);
assert.equal(nodes['attendance-section'].hidden,false);
assert.equal(nodes['attendance-button'].hidden,false);
assert.match(nodes.stamp.textContent,/backup switch/);
vm.runInContext("last.confirmedAt=new Date(Date.now()-451000).toISOString();render();renderAttendance();",context);
assert.equal(nodes['attendance-section'].hidden,true);
assert.equal(nodes['attendance-button'].hidden,true);
